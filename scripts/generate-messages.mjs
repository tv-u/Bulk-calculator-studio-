const ALL_CODES = [
  'en','hi','bn','te','mr','ta','ur','gu','kn','ml','pa','or','as','ne','si',
  'zh-CN','zh-TW','ja','ko','vi','th','id','ms','fil','ar','fa','he','tr',
  'es','fr','de','pt','it','nl','pl','ru','uk','sv','no','da','fi','el','cs',
  'ro','hu','bg','sr','hr','sk','sw',
];

const totalKeys = Object.keys(BASE_EN).length;
const audit = [];

for (const code of ALL_CODES) {
  const overrides = TRANSLATIONS[code] || {};
  const merged = { ...BASE_EN, ...overrides };
  const localizedCount = code === 'en' ? totalKeys : Object.keys(overrides).length;
  fs.writeFileSync(path.join(OUT_DIR, `${code}.json`), JSON.stringify(merged, null, 2), 'utf8');
  audit.push({
    code,
    totalKeys,
    localizedKeys: localizedCount,
    fallbackEnglishKeys: totalKeys - localizedCount,
    coveragePct: Number(((localizedCount / totalKeys) * 100).toFixed(1)),
  });
}

fs.writeFileSync(REPORT_FILE, JSON.stringify({ generatedAt: new Date().toISOString(), languages: audit }, null, 2), 'utf8');
console.log(`Generated ${ALL_CODES.length} locale files in public/messages/ and i18n-audit.json`);
